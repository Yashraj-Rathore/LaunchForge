  private static void evaluation(
      ArrayNode cases,
      String name,
      String flagKey,
      String requestedType,
      Object defaultValue,
      ObjectNode attributes,
      Object expectedValue,
      String reason,
      String variation,
      String rule) {
    ObjectNode item = cases.addObject();
    item.put("name", name);
    item.put("flagKey", flagKey);
    item.put("requestedType", requestedType);
    item.set("defaultValue", SnapshotTestData.MAPPER.valueToTree(defaultValue));
    item.put("contextKey", "subject-1");
    item.set(
        "attributes", attributes == null ? SnapshotTestData.MAPPER.createObjectNode() : attributes);
    ObjectNode expected = item.putObject("expected");
    expected.set("value", SnapshotTestData.MAPPER.valueToTree(expectedValue));
    expected.put("reason", reason);
    expected.put("revision", 42);
    if (variation != null) {
      expected.put("variation", variation);
    }
    if (rule != null) {
      expected.put("rule", rule);
    }
  }

  private static void addMalformedSnapshots(ArrayNode cases, ObjectNode valid) {
    ObjectNode unsupported = valid.deepCopy();
    unsupported.put("algorithmVersion", 2);
    malformed(cases, "unsupported-algorithm", SnapshotTestData.withRecomputedChecksum(unsupported));

    ObjectNode unsafe = SnapshotTestData.root(1);
    unsafe.withObject("flags").set("unsafe-number", typedFlag("number", 0, 9_007_199_254_740_992d));
    malformed(cases, "unsafe-integer", SnapshotTestData.withRecomputedChecksum(unsafe));

    ObjectNode invalidWeights = valid.deepCopy();
    ((ObjectNode)
            invalidWeights
                .withObject("flags")
                .withObject(FLAG_KEY)
                .withObject("rollout")
                .withArray("weights")
                .get(0))
        .put("weight", 49_999);
    malformed(
        cases, "invalid-rollout-total", SnapshotTestData.withRecomputedChecksum(invalidWeights));

    ObjectNode checksum = valid.deepCopy();
    checksum.put("revision", 99);
    malformed(cases, "checksum-mismatch", checksum.toString());
    malformed(cases, "duplicate-property", "{\"schemaVersion\":1,\"schemaVersion\":1}");
  }

  private static void malformed(ArrayNode cases, String name, String snapshot) {
    ObjectNode item = cases.addObject();
    item.put("name", name);
    item.put("snapshot", snapshot);
    item.put("expected", "REJECTED");
  }

  private static String findSubject(int target) {
    for (int candidate = 0; candidate < 2_000_000; candidate++) {
      String subject = "boundary-" + candidate;
      if (referenceBucket(FLAG_KEY, SALT, subject) == target) {
        return subject;
      }
    }
    throw new IllegalStateException("Reference generator did not find boundary subject");
  }

  private static int referenceBucket(String flagKey, String salt, String subject) {
    try {
      byte[] digest =
          MessageDigest.getInstance("SHA-256")
              .digest((flagKey + '\n' + salt + '\n' + subject).getBytes(StandardCharsets.UTF_8));
      long prefix = 0;
      for (int index = 0; index < 8; index++) {
        prefix = (prefix << 8) | Byte.toUnsignedLong(digest[index]);
      }
      return (int) Long.remainderUnsigned(prefix, 100_000);
    } catch (NoSuchAlgorithmException exception) {
      throw new IllegalStateException(exception);
    }
  }

  private static String canonical(String json) {
    try {
      return new JsonCanonicalizer(json).getEncodedString();
    } catch (IOException exception) {
      throw new IllegalStateException(exception);
    }
  }

  private static String sha256(String value) {
    try {
      return HexFormat.of()
          .formatHex(
              MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8)));
    } catch (NoSuchAlgorithmException exception) {
      throw new IllegalStateException(exception);
    }
  }
