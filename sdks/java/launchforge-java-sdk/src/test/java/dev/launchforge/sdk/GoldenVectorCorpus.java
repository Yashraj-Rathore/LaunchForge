  private static final String FLAG_KEY = "rollout-flag";
  private static final String SALT = "stable_salt_1234";

  private GoldenVectorCorpus() {}

  static String generate() {
    ObjectNode corpus = SnapshotTestData.MAPPER.createObjectNode();
    corpus.put("corpusVersion", 1);
    corpus.put("schemaVersion", 1);
    corpus.put("algorithmVersion", 1);
    corpus.put(
        "generator",
        "GoldenVectorCorpus.java; SHA-256 outputs are generated by an independent reference function");
    corpus.set(
        "reasonCodes",
        SnapshotTestData.MAPPER.valueToTree(
            List.of(
                "FLAG_NOT_FOUND",
                "FLAG_DISABLED",
                "DEFAULT_VARIATION",
                "RULE_MATCH",
                "ROLLOUT_MATCH",
                "MISSING_ROLLOUT_KEY",
                "TYPE_MISMATCH",
                "INVALID_CONFIG",
                "SNAPSHOT_UNAVAILABLE",
                "ERROR_DEFAULT")));
    addRolloutVectors(corpus.putArray("rolloutVectors"));
    addOperatorCases(corpus.putArray("operatorCases"));
    ObjectNode snapshot = evaluationSnapshot();
    corpus.set("evaluationSnapshot", snapshot);
    addEvaluationCases(corpus.putArray("evaluationCases"));
    addMalformedSnapshots(corpus.putArray("malformedSnapshots"), snapshot);
    corpus.put("corpusChecksum", sha256(canonical(corpus.toString())));
    return canonical(corpus.toString()) + '\n';
  }

  private static void addRolloutVectors(ArrayNode vectors) {
    rolloutVector(vectors, "ascii", "checkout", SALT, "user-123");
    rolloutVector(vectors, "unicode", "unicode-flag", SALT, "Zoë-東京");
    rolloutVector(vectors, "signed-looking", "signed-flag", SALT, "-00042");
    rolloutVector(vectors, "line-break-subject", "line-break-flag", SALT, "line-one\nline-two");
    rolloutVector(vectors, "changed-salt", "unicode-flag", "changed_salt_1234", "Zoë-東京");
    String lowerBoundary = findSubject(49_999);
    String upperBoundary = findSubject(50_000);
    rolloutVector(vectors, "last-first-allocation-bucket", FLAG_KEY, SALT, lowerBoundary);
    rolloutVector(vectors, "first-second-allocation-bucket", FLAG_KEY, SALT, upperBoundary);

    ObjectNode sample = vectors.addObject();
    sample.put("name", "deterministic-ten-percent-sample");
    sample.put("flagKey", FLAG_KEY);
    sample.put("salt", SALT);
    sample.put("subjectPrefix", "sample-");
    sample.put("sampleSize", 10_000);
    sample.put("thresholdExclusive", 10_000);
    int selected = 0;
    for (int index = 0; index < 10_000; index++) {
      if (referenceBucket(FLAG_KEY, SALT, "sample-" + index) < 10_000) {
        selected++;
      }
    }
    sample.put("selectedCount", selected);
  }

  private static void rolloutVector(
      ArrayNode vectors, String name, String flagKey, String salt, String subject) {
    ObjectNode vector = vectors.addObject();
    vector.put("name", name);
    vector.put("flagKey", flagKey);
    vector.put("salt", salt);
    vector.put("subject", subject);
    vector.put("bucket", referenceBucket(flagKey, salt, subject));
  }

