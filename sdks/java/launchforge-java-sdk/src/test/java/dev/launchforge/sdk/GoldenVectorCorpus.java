  private static void operator(
      ArrayNode cases,
      String name,
      String type,
      String operator,
      List<?> configured,
      Object contextValue,
      boolean expectedMatch) {
    ObjectNode item = cases.addObject();
    item.put("name", name);
    item.put("attributeType", type);
    item.put("operator", operator);
    item.set("configuredValues", SnapshotTestData.MAPPER.valueToTree(configured));
    item.put("contextPresent", contextValue != null);
    if (contextValue != null) {
      item.set("contextValue", SnapshotTestData.MAPPER.valueToTree(contextValue));
    }
    item.put("expectedMatch", expectedMatch);
  }

  private static ObjectNode evaluationSnapshot() {
    ObjectNode root = SnapshotTestData.root(42);
    ObjectNode flags = root.withObject("flags");
    flags.set("boolean-default", SnapshotTestData.booleanFlag(true, false, true));
    flags.set("disabled", SnapshotTestData.booleanFlag(false, false, true));
    flags.set("string-default", typedFlag("string", "safe", "hello"));
    flags.set("number-default", typedFlag("number", 0, 12.5));
    ObjectNode jsonFlag =
        typedFlag(
            "json",
            SnapshotTestData.MAPPER.createObjectNode(),
            SnapshotTestData.MAPPER.createObjectNode().put("theme", "forge").put("count", 2));
    flags.set("json-default", jsonFlag);
    ObjectNode ruled = SnapshotTestData.booleanFlag(true, false, true);
    ruled.put("defaultVariation", "off");
    SnapshotTestData.addRule(
        ruled,
        "unicode-rule",
        SnapshotTestData.condition(
            "name", "string", "EQUALS", SnapshotTestData.MAPPER.valueToTree("Zoë")),
        "on");
    flags.set("rule-flag", ruled);
    ObjectNode rolloutFlag = SnapshotTestData.booleanFlag(true, false, true);
    rolloutFlag.put("defaultVariation", "off");
    ObjectNode rollout = rolloutFlag.putObject("rollout");
    rollout.put("attribute", "userId");
    rollout.put("salt", SALT);
    rollout.putArray("weights").addObject().put("variation", "on").put("weight", 50_000);
    ((ArrayNode) rollout.get("weights")).addObject().put("variation", "off").put("weight", 50_000);
    flags.set(FLAG_KEY, rolloutFlag);
    return SnapshotTestData.copyOf(SnapshotTestData.canonicalSnapshot(root));
  }

  private static ObjectNode typedFlag(String type, Object off, Object on) {
    ObjectNode flag = SnapshotTestData.MAPPER.createObjectNode();
    flag.put("type", type);
    flag.put("enabled", true);
    flag.put("clientVisible", true);
    ArrayNode variations = flag.putArray("variations");
    variations.addObject().put("id", "off").set("value", SnapshotTestData.MAPPER.valueToTree(off));
    variations.addObject().put("id", "on").set("value", SnapshotTestData.MAPPER.valueToTree(on));
    flag.put("offVariation", "off");
    flag.put("defaultVariation", "on");
    flag.putArray("rules");
    return flag;
  }

